#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn expression_contains_elects_or_arms() {
        assert!(expression_contains("MPL-2.0", "MPL-2.0"));
        assert!(expression_contains(
            "LGPL-3.0-or-later OR MPL-2.0",
            "MPL-2.0"
        ));
        assert!(!expression_contains("MIT OR Apache-2.0", "MPL-2.0"));
        assert!(!expression_contains("LGPL-3.0-or-later", "MPL-2.0"));
    }

    #[test]
    fn document_lists_crates_sorted_with_sections() {
        // Fixtures exercise shape: sorted table, MPL election text, CC0
        // section, no section for plain MIT.
        let meta = serde_json_lite::parse(
            r#"{"packages":[
                {"name":"zeta","version":"1.0","license":"MIT","repository":"https://example.com/zeta"},
                {"name":"option-ext","version":"0.2.0","license":"MPL-2.0","homepage":"https://example.com/oe"},
                {"name":"priority-queue","version":"2.7.0","license":"LGPL-3.0-or-later OR MPL-2.0","repository":"https://example.com/pq"},
                {"name":"notify","version":"8.2.0","license":"CC0-1.0","repository":""},
                {"name":"icu_normalizer","version":"2.3.0","license":"Unicode-3.0","repository":"https://example.com/icu"}
            ]}"#,
        )
        .expect("parses");
        let doc = build_document(&meta).expect("document");
        // Sorted by name: icu < notify < option-ext < priority-queue < zeta.
        let icu = doc.find("| icu_normalizer |").expect("icu row");
        let notify = doc.find("| notify |").expect("notify row");
        let oe = doc.find("| option-ext |").expect("option-ext row");
        let pq = doc.find("| priority-queue |").expect("priority-queue row");
        let zeta = doc.find("| zeta |").expect("zeta row");
        assert!(
            icu < notify && notify < oe && oe < pq && pq < zeta,
            "sorted: {doc}"
        );
        // Explicit sections exist with the required compliance text.
        assert!(doc.contains("## MPL-2.0 packages"), "{doc}");
        assert!(doc.contains("elects the MPL-2.0 term"), "{doc}");
        assert!(
            doc.contains("§3.2"),
            "MPL section carries the 3.2 pointer: {doc}"
        );
        assert!(doc.contains("## Unicode-3.0 packages"), "{doc}");
        assert!(doc.contains("## CC0-1.0 packages"), "{doc}");
        // URL fallback: homepage preferred, repository second, dash when absent.
        assert!(doc.contains("| https://example.com/oe |"), "{doc}");
        assert!(doc.contains("| - |"), "empty URL degrades to dash: {doc}");
    }

    #[test]
    fn vendored_boringtun_gets_a_modified_copy_note() {
        // The archive ships the BSD-3-Clause text and this notice: the note
        // must name the modification and point at the patch record, else the
        // binary distribution is a licence violation (BSD-3-Clause §2).
        let meta = serde_json_lite::parse(
            r#"{"packages":[
                {"name":"boringtun","version":"0.7.1","license":"BSD-3-Clause","repository":"https://github.com/cloudflare/boringtun"}
            ]}"#,
        )
        .expect("parses");
        let doc = build_document(&meta).expect("document");
        assert!(doc.contains("## Vendored packages"), "{doc}");
        assert!(doc.contains("modified copy"), "{doc}");
        assert!(
            doc.contains("third_party/boringtun/QCORE_PATCHES.md"),
            "{doc}"
        );
        assert!(doc.contains("LICENSE.md"), "{doc}");
    }

    #[test]
    fn missing_license_fails_closed() {
        let meta = serde_json_lite::parse(
            r#"{"packages":[{"name":"ghost","version":"1.0","license":""}]}"#,
        )
        .expect("parses");
        let err = build_document(&meta).expect_err("no-license crate fails");
        assert!(err.contains("declares no license"), "{err}");
    }

    #[test]
    fn duplicate_package_entries_dedup() {
        let meta = serde_json_lite::parse(
            r#"{"packages":[
                {"name":"a","version":"1.0","license":"MIT"},
                {"name":"a","version":"1.0","license":"MIT"}
            ]}"#,
        )
        .expect("parses");
        let doc = build_document(&meta).expect("document");
        assert_eq!(doc.matches("| a |").count(), 1, "deduped: {doc}");
    }
}
